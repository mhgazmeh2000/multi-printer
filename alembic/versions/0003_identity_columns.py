# -*- coding: utf-8 -*-
"""
0003_identity_columns — تبدیل هفت شناسه‌ی `BIGSERIAL` به `IDENTITY` روی PostgreSQL (فاز E.4.2).

چرا؟
----
`0001` عمداً `BIGSERIAL` (توالی + `nextval` به‌عنوان default) ساخت تا «شکل امروزِ»
SQLite را بازتولید کند. روی PostgreSQL شکل استاندارد و توصیه‌شده‌ی اسکیمای مدرن
`GENERATED BY DEFAULT AS IDENTITY` است: توالی به‌عنوان شیء مستقل وجود ندارد که کسی
اشتباهی دستکاری کند، مالکیت و طول عمرش به ستون گره خورده، و `pg_dump`/بازگردانی
تمیزتر است. رفتار «خودافزایی» در عمل یکی است.

هفت جدول (همان هفت جدولی که در SQLite `AUTOINCREMENT` دارند):

    logs · toner_history · sensor_readings · users · security_events ·
    yield_samples · toner_snapshots_v2

روی SQLite این migration **no-op** است
--------------------------------------
`INTEGER PRIMARY KEY AUTOINCREMENT` تنها سازوکار SQLite برای شناسه‌ی هم‌معنای
IDENTITY است و schema امروزِ برنامه همین است. این migration فقط بررسی می‌کند که
هر هفت جدول آن‌ را داشته باشند؛ اگر جدولی نداشته باشد، اجرا با پیام روشن متوقف
می‌شود (schema ناهم‌خوان، نه رد شدن بی‌صدا).

چهار گام روی PG (هر سه یافته اندازه‌گیری‌شده، نه حدس)
-----------------------------------------------------
۱) `ADD GENERATED BY DEFAULT AS IDENTITY` وقتی ستون `DEFAULT nextval(...)` دارد رد
   می‌شود:

       ERROR: column "id" of relation "…" already has a default value

   پس اول `DROP DEFAULT`.
۲) توالی قدیمی (`<table>_id_seq`) مالکیتش به ستون گره خورده بود؛ با `DROP DEFAULT`
   مالکیت از بین نمی‌رود ولی **بلااستفاده** می‌ماند. پاک می‌شود، وگرنه باقیمانده‌ی
   اسکیما می‌شود (و در `information_schema.sequences` سردرگمی می‌سازد).
۳) `ADD GENERATED BY DEFAULT AS IDENTITY` توالی **تازه‌ای** می‌سازد که از ۱ شروع
   می‌کند — روی جدولِ داده‌دار یعنی تضاد کلید در اولین درج بعدی. اندازه‌گیری شد:
   روی جدولی با idهای ۱..۳ (بدون کلید) مقادیر تکراری تولید می‌کرد. پس بلافاصله
   `ALTER COLUMN id RESTART WITH <max(id)+1>` اجرا می‌شود (جدول خالی ⇒ ۱).

`BY DEFAULT` (نه `ALWAYS`) انتخاب شد تا درج صریح `id` همچنان ممکن بماند: مسیر
`import_db` (و هر ابزار مهاجرت داده) idها را صریح می‌آورد و `ALWAYS` آن‌ها را
می‌شکست.

ایمنی
----
• **idempotent:** ستونی که از قبل `is_identity = 'YES'` است رد می‌شود؛
• همچنان `RESTART WITH` را از نو تنظیم می‌کند (بی‌خطر و مفید: اگر داده‌ای بعد از
  اجرای قبلی صریح درج شده باشد، مقدار درست می‌شود)؛
• **مسیر برگشت:** `downgrade` به `BIGSERIAL` برمی‌گردد: `DROP IDENTITY` ⇒ ساخت توالی
  با همان نام تاریخی ⇒ `SET DEFAULT nextval(...)` ⇒ `OWNED BY` ⇒ `setval` روی
  `max(id)`.
"""
from __future__ import annotations

import logging

import sqlalchemy as sa
from alembic import op

revision = "0003"
down_revision = "0002"
branch_labels = None
depends_on = None

log = logging.getLogger("alembic.runtime.migration")

#: جدول‌هایی که شناسه‌شان باید IDENTITY شود (همان هفت جدول AUTOINCREMENT در SQLite).
IDENTITY_TABLES = (
    "logs",
    "toner_history",
    "sensor_readings",
    "users",
    "security_events",
    "yield_samples",
    "toner_snapshots_v2",
)


def _is_postgres() -> bool:
    return op.get_bind().dialect.name == "postgresql"


def _identity_state(conn, table: str):
    """``(is_identity, column_default)`` ستون id از ``information_schema``."""
    row = conn.execute(
        sa.text(
            "SELECT is_identity, column_default FROM information_schema.columns "
            "WHERE table_schema = current_schema() "
            "AND table_name = :t AND column_name = 'id'"
        ),
        {"t": table},
    ).fetchone()
    return (None, None) if row is None else (row[0], row[1])


def _max_id(conn, table: str):
    return conn.execute(sa.text(f'SELECT max(id) FROM "{table}"')).fetchone()[0]


def _sqlite_has_autoincrement(conn, table: str) -> bool:
    row = conn.execute(
        sa.text("SELECT sql FROM sqlite_master WHERE type='table' AND name = :t"),
        {"t": table},
    ).fetchone()
    if row is None or row[0] is None:
        return False
    return "AUTOINCREMENT" in str(row[0]).upper()


def upgrade() -> None:
    conn = op.get_bind()

    if not _is_postgres():
        missing = [t for t in IDENTITY_TABLES if not _sqlite_has_autoincrement(conn, t)]
        if missing:
            raise RuntimeError(
                "0003_identity_columns: این جدول‌ها در SQLite «AUTOINCREMENT» ندارند: "
                + ", ".join(missing) +
                " — schema با انتظار این migration هم‌خوان نیست (کار E.4.2)."
            )
        log.info(
            "0003_identity_columns: SQLite ⇒ no-op (INTEGER PRIMARY KEY AUTOINCREMENT "
            "هم‌معنای IDENTITY است). %d جدول بررسی و تأیید شد.", len(IDENTITY_TABLES)
        )
        return

    for table in IDENTITY_TABLES:
        is_identity, default = _identity_state(conn, table)
        if is_identity is None:
            raise RuntimeError(
                f"0003_identity_columns: ستون id جدول «{table}» در دیتابیس نیست."
            )

        seq_name = f"{table}_id_seq"
        if is_identity == "YES":
            if default is None:
                # وضعیت سالم و موردانتظار: توالی داخلی IDENTITY در column_default دیده نمی‌شود.
                log.info("0003_identity_columns: %s.id از قبل IDENTITY است ⇒ رد شد.", table)
            else:
                log.info("0003_identity_columns: %s.id IDENTITY است (default=%s) ⇒ رد شد.",
                         table, default)
        else:
            # گام ۱: default قدیمی (nextval) باید برود، وگرنه ADD IDENTITY رد می‌شود.
            op.execute(f'ALTER TABLE "{table}" ALTER COLUMN id DROP DEFAULT')
            # گام ۲: توالی قدیمی بلااستفاده است؛ پاک می‌شود (اگر وجود داشته باشد).
            op.execute(f'DROP SEQUENCE IF EXISTS "{seq_name}"')
            # گام ۳: توالی تازه‌ی IDENTITY.
            op.execute(
                f'ALTER TABLE "{table}" ALTER COLUMN id '
                f"ADD GENERATED BY DEFAULT AS IDENTITY"
            )
            log.info("0003_identity_columns: %s.id ⇒ IDENTITY (BY DEFAULT)", table)

        # گام ۴ (همیشه): هم‌ترازی توالی با داده‌ی موجود.
        max_id = _max_id(conn, table)
        restart = 1 if max_id is None else int(max_id) + 1
        op.execute(f'ALTER TABLE "{table}" ALTER COLUMN id RESTART WITH {restart}')
        log.info("0003_identity_columns: %s.id ⇒ RESTART WITH %d (max_id=%s)",
                 table, restart, max_id)


def downgrade() -> None:
    conn = op.get_bind()

    if not _is_postgres():
        log.info("0003_identity_columns (downgrade): SQLite ⇒ no-op.")
        return

    for table in IDENTITY_TABLES:
        is_identity, _default = _identity_state(conn, table)
        if is_identity is None:
            raise RuntimeError(
                f"0003_identity_columns (downgrade): ستون id جدول «{table}» نیست."
            )
        if is_identity != "YES":
            log.info("0003_identity_columns (downgrade): %s.id از قبل IDENTITY نیست ⇒ رد شد.",
                     table)
        else:
            op.execute(f'ALTER TABLE "{table}" ALTER COLUMN id DROP IDENTITY')

        seq_name = f"{table}_id_seq"
        op.execute(f'CREATE SEQUENCE IF NOT EXISTS "{seq_name}"')
        op.execute(
            f'ALTER TABLE "{table}" ALTER COLUMN id SET DEFAULT nextval(\'{seq_name}\')'
        )
        op.execute(f'ALTER SEQUENCE "{seq_name}" OWNED BY "{table}".id')

        max_id = _max_id(conn, table)
        if max_id is None:
            op.execute(f"SELECT setval('{seq_name}', 1, false)")
        else:
            op.execute(f"SELECT setval('{seq_name}', {int(max_id)}, true)")
        log.info("0003_identity_columns (downgrade): %s.id ⇒ BIGSERIAL (seq=%s, max_id=%s)",
                 table, seq_name, max_id)
